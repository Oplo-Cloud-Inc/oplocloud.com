#!/usr/bin/env node
/* Writes learn/kern-outline.js: what is inside every lab unit, without the unit.

   Kern's pages draw a whole course at once: the course wheel has a ring for each
   unit and a segment for each lesson; the unit list says "5 of 8"; Home names the
   next three lessons; Practice and Progress name every skill. The units
   themselves are 100–160 KB each and load on demand, so none of those pages can
   read them. This reads them once, here, and keeps only the outline: lesson
   titles and lengths, the skills, the quizzes, and the size of the unit test.

   Run it whenever a lab unit's lessons or skills change (the numbers it holds
   are counts, so a rewritten sentence does not need it, an added lesson does):

       node tools/kern_outline.mjs

   It serves learn/ itself on a spare port, opens it in a headless browser with
   the network shut, loads each unit through OPLO_LAB.load, and writes the file.
   Playwright is found the way Node finds any module: in a node_modules above
   this folder.                                                              */
import { createRequire } from "module";
import http from "http";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const require = createRequire(import.meta.url);
const { chromium } = require("playwright");
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "learn", "kern-outline.js");
const TYPES = { ".html": "text/html", ".js": "text/javascript", ".css": "text/css", ".json": "application/json",
  ".svg": "image/svg+xml", ".png": "image/png", ".jpg": "image/jpeg", ".webp": "image/webp", ".woff2": "font/woff2" };

const server = http.createServer((req, res) => {
  let p = decodeURIComponent(req.url.split("?")[0]);
  if (p.endsWith("/")) p += "index.html";
  const file = path.join(ROOT, p);
  if (!file.startsWith(ROOT)) { res.writeHead(403).end(); return; }
  fs.readFile(file, (err, buf) => {
    if (err) { res.writeHead(404).end(); return; }
    res.writeHead(200, { "Content-Type": TYPES[path.extname(file)] || "application/octet-stream", "Cache-Control": "no-store" });
    res.end(buf);
  });
});
await new Promise((ok) => server.listen(0, ok));
const port = server.address().port;

const browser = await chromium.launch();
const ctx = await browser.newContext();
await ctx.route((u) => !/^(localhost|127\.0\.0\.1)$/.test(u.hostname), (r) => r.abort());
// Kern's catalogue has courses edu's does not (Grade 1 Math, Precalculus), so ask for Kern's.
await ctx.addInitScript(() => { try { localStorage.setItem("oplo.kern", "1"); } catch (e) { /* no storage */ } });
const page = await ctx.newPage();
const problems = [];
page.on("pageerror", (e) => problems.push(e.message));
await page.goto(`http://localhost:${port}/learn/index.html`, { waitUntil: "load" });
await page.waitForFunction(() => window.OPLO_LAB && window.OPLO_SCHOOL, null, { timeout: 15000 });

const plan = await page.evaluate(() => window.OPLO_SCHOOL.courses()
  .filter((c) => c.units && c.units.some((u) => u.lab))
  .map((c) => ({ id: c.id, units: c.units.map((u, i) => (u.lab && window.OPLO_LAB.has(c.id, i + 1) ? i + 1 : 0)).filter(Boolean) })));

const out = {};
for (const c of plan) {
  out[c.id] = {};
  for (const n of c.units) {
    try {
      out[c.id][n] = await page.evaluate(async ([id, n]) => {
        const plain = (t) => String(t == null ? "" : t).replace(/<[^>]+>/g, "").replace(/\$([^$]+)\$/g, "$1")
          .replace(/\\[a-z]+/g, "").replace(/[{}*]/g, "").replace(/\s+/g, " ").trim();
        const u = await window.OPLO_LAB.load(id, n);
        return {
          // title, minutes, the tag a lesson wears instead of a number (or ""), 1 when it is a reading,
          // steps, and the lesson's version (a rewritten lesson is a new record: "unit:k~v")
          l: u.lessons.map((l) => [plain(l.title), l.mins || Math.max(4, Math.round(l.steps.length * 0.9)), l.tag || "", l.kind === "read" ? 1 : 0, l.steps.length, l.v || 0]),
          // id, title
          s: u.skills.map((s) => [s.id, plain(s.title)]),
          // title, the lesson it comes after, how many questions
          q: u.quizzes.map((q) => [plain(q.title), q.after, q.skills.length * (q.per || 2)]),
          // questions in the unit test
          t: u.skills.length
        };
      }, [c.id, n]);
    } catch (e) {
      problems.push(`${c.id} unit ${n}: ${e.message}`);
    }
  }
}
await browser.close();
server.close();

const units = Object.values(out).reduce((a, c) => a + Object.keys(c).length, 0);
const lessons = Object.values(out).reduce((a, c) => a + Object.values(c).reduce((b, u) => b + u.l.length, 0), 0);
const body = JSON.stringify(out).replace(/<\/script/gi, "<\\/script");
fs.writeFileSync(OUT,
  "/* Generated by tools/kern_outline.mjs. Do not edit: run it again.\n" +
  "   The outline of every lab unit, so a page that draws a whole course need not load its units.\n" +
  "   KERN_OUTLINE[courseId][unitNumber] = { l: [[title, minutes, tag, isReading, steps, version]], s: [[skillId, title]],\n" +
  "     q: [[title, afterLesson, questions]], t: unit-test questions }                                  */\n" +
  "window.KERN_OUTLINE = " + body + ";\n");
console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(out).length} courses, ${units} units, ${lessons} lessons, ${(fs.statSync(OUT).size / 1024).toFixed(0)} KB`);
if (problems.length) { console.log("PROBLEMS:\n  " + problems.join("\n  ")); process.exitCode = 1; }
